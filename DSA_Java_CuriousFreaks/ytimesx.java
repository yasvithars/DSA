import java.util.*;
public class ytimesx {
    public static void main(String[] args){
        Scanner scan = new Scanner(System.in);

        System.out.println("Enter x");
        int x = scan.nextInt();
        System.out.println("Enter y");
        int y = scan.nextInt();

        for(int i=1; i<=y; i++){
            System.out.println(x);
        }
    }
}
